const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const ROOT = path.resolve(__dirname, '..');
const check = (condition, message) => { if (!condition) throw new Error(message); };
function compileUnits(input) {
  check(Array.isArray(input) && input.length > 0, '至少需要一个单元');
  const units = [...input].sort((a,b) => a.id-b.id);
  const unitIds = new Set(), levelIds = new Set(), questionIds = new Set();
  for (const unit of units) {
    check(Number.isInteger(unit.id) && unit.id > 0 && !unitIds.has(unit.id), '单元编号重复或无效');
    unitIds.add(unit.id);
    for (const key of ['label','title','heading','intro','icon','badge','source','summary']) check(typeof unit[key] === 'string' && unit[key].trim(), `单元 ${unit.id} 缺少 ${key}`);
    check(Array.isArray(unit.levels) && unit.levels.length > 0, `单元 ${unit.id} 没有关卡`);
    check(Array.isArray(unit.questions) && unit.questions.length > 0, `单元 ${unit.id} 没有题目`);
    const localLevels = new Set();
    for (const level of unit.levels) {
      check(typeof level.id === 'string' && !levelIds.has(level.id) && level.unit === unit.id, `关卡 ${level.id} 重复或单元错误`);
      check(['mint','peach','yellow'].includes(level.color), `关卡 ${level.id} 颜色无效`);
      for (const key of ['title','sub','icon','badge']) check(typeof level[key] === 'string' && level[key], `关卡 ${level.id} 缺少 ${key}`);
      check(Number.isFinite(level.minutes) && level.minutes > 0, `关卡 ${level.id} 时长无效`);
      levelIds.add(level.id); localLevels.add(level.id);
    }
    for (const q of unit.questions) {
      check(typeof q.id === 'string' && q.id && !questionIds.has(q.id), `题目 ${q.id} 编号重复或无效`);
      check(localLevels.has(q.level), `题目 ${q.id} 指向不存在的本单元关卡`);
      check(['choice','multi','order'].includes(q.type), `题目 ${q.id} 题型不支持`);
      for (const key of ['prompt','hint','explain']) check(typeof q[key] === 'string' && q[key].trim(), `题目 ${q.id} 缺少 ${key}`);
      check(Array.isArray(q.options) && q.options.length >= 2 && q.options.every(x=>typeof x==='string' && x.length), `题目 ${q.id} 选项无效`);
      check(q.type === 'choice' ? Number.isInteger(q.answer) : Array.isArray(q.answer) && q.answer.length > 0, `题目 ${q.id} 答案结构错误`);
      const answers = Array.isArray(q.answer) ? q.answer : [q.answer];
      check(answers.every(i=>Number.isInteger(i) && i>=0 && i<q.options.length), `题目 ${q.id} 答案越界`);
      check(new Set(answers).size===answers.length, `题目 ${q.id} 重复使用词块，请为重复词块提供不同选项位置`);
      questionIds.add(q.id);
    }
    for (const level of unit.levels) check(unit.questions.some(q=>q.level===level.id), `关卡 ${level.id} 没有题目`);
  }
  const levels = units.flatMap(u=>u.levels), questions=units.flatMap(u=>u.questions);
  const metadata=units.map(({levels:ls,questions:qs,...u})=>({...u,levelCount:ls.length,questionCount:qs.length}));
  return {schema:2,units:metadata,levels,questions,stats:{unitCount:units.length,levelCount:levels.length,questionCount:questions.length,maxStars:levels.length*3,maxXP:questions.length*10}};
}
function readUnits(directory=path.join(ROOT,'content/units')) {
  return fs.readdirSync(directory).filter(f=>f.endsWith('.json')).sort().map(f=>JSON.parse(fs.readFileSync(path.join(directory,f),'utf8')));
}
function bundle(catalog) {
  // Escape '<' so a future text entry cannot end the inline script in the offline HTML.
  const json=JSON.stringify(catalog).replace(/</g,'\\u003c');
  return `// Generated by scripts/build-content.cjs. Edit content/units/*.json instead.\nconst CATALOG=${json};\nconst UNITS=CATALOG.units;\nconst LEVELS=CATALOG.levels;\nconst QUESTIONS=CATALOG.questions;\n`;
}
function build() {
  const catalog=compileUnits(readUnits());
  fs.mkdirSync(path.join(ROOT,'dist'),{recursive:true});
  const assets={'questions.js':bundle(catalog),'app.js':fs.readFileSync(path.join(ROOT,'src/app.js'),'utf8'),'styles.css':fs.readFileSync(path.join(ROOT,'src/styles.css'),'utf8')};
  let html=fs.readFileSync(path.join(ROOT,'src/index.html'),'utf8').replace('{{DESCRIPTION}}',`语文探险岛：四年级上册，${catalog.stats.unitCount}个单元、${catalog.stats.questionCount}个互动任务。练读音、拼汉字、学词语、读名句，在即时反馈中快乐成长。`);
  for (const [name,body] of Object.entries(assets)) {
    fs.writeFileSync(path.join(ROOT,'dist',name),body);
    const hash=crypto.createHash('sha256').update(body).digest('hex').slice(0,10);
    html=html.replaceAll(`{{${name}}}`,`${name}?v=${hash}`);
  }
  fs.writeFileSync(path.join(ROOT,'dist/index.html'),html);
  let offline=html.replace(/<link rel="stylesheet" href="styles\.css\?v=[^"]+">/,'<style>'+assets['styles.css']+'</style>');
  for (const name of ['questions.js','app.js']) offline=offline.replace(new RegExp(`<script src="${name.replace('.','\\.')}\\?v=[^"]+"></script>`),()=>'<script>'+assets[name]+'</script>');
  check(!/<script src=|<link rel="stylesheet"/.test(offline),'离线版本仍引用外部文件');
  fs.writeFileSync(path.join(ROOT,'dist/offline.html'),offline);
  console.log(`Built ${catalog.stats.unitCount} units / ${catalog.stats.levelCount} levels / ${catalog.stats.questionCount} questions; offline.html included.`);
  return catalog;
}
module.exports={compileUnits,readUnits,bundle,build};
if(require.main===module)build();
