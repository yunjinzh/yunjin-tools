// node --loader ./tools/exhibition/three-loader.mjs tools/bake-cpu-geometry.mjs
import {writeFile,mkdir} from 'node:fs/promises';
import {gzipSync} from 'node:zlib';
import {sourceCpuLandmark} from '../dist/cpu-landmarks.js';
import {landmarks,sourceLandmarkFootprints} from '../dist/landmarks.js';
import {getCpuCbdMeshes} from '../dist/urban/cbd.js';
import {walkingTriangles} from './walking-triangles.mjs';
import {project} from '../dist/navigation.js';

const out=new URL('../dist/urban/cpu/',import.meta.url);
await mkdir(out,{recursive:true});
const masks={};
for(const {id} of landmarks)masks[id]=sourceLandmarkFootprints(id);
await writeFile(new URL('../dist/data/landmark-masks.js',import.meta.url),
  '// Generated by tools/bake-cpu-geometry.mjs from the rendered landmark footprints.\nexport const landmarkMasks='+JSON.stringify(masks)+';\n');
const walking={};
for(const id of ['tiantan','palace','tiananmen']){
  const t=walkingTriangles(id);walking[id]=Buffer.from(t.buffer).toString('base64');
}
await writeFile(new URL('../dist/data/walking-triangles.js',import.meta.url),
  '// Float64 XYZ-plane triangles from the authored models; generated by tools/bake-cpu-geometry.mjs.\nexport const walkingData='+JSON.stringify(walking)+';\n');
async function pack(name,models){
  let size=0;const chunks=[],records=[];
  for(const m of models){
    const meta={},attributes={};
    for(const [key,value] of Object.entries(m)){
      if(!ArrayBuffer.isView(value)){meta[key]=value;continue;}
      const data=key==='index'&&m.pos.length/3<=65536?new Uint16Array(value):value;
      const offset=(size+3)&~3;
      if(offset>size)chunks.push(Buffer.alloc(offset-size));
      const bytes=Buffer.from(data.buffer,data.byteOffset,data.byteLength);chunks.push(bytes);
      attributes[key]=[data.constructor.name,offset,data.length];size=offset+bytes.length;
    }
    records.push({meta,attributes});
  }
  const meta=Buffer.from(JSON.stringify(records)),head=Buffer.alloc((8+meta.length+3)&~3);
  head.write('BJC1');head.writeUInt32LE(meta.length,4);meta.copy(head,8);
  const packed=gzipSync(Buffer.concat([head,...chunks]),{level:9});
  await writeFile(new URL(name+'.bin.gz',out),packed);
  console.log(name,models.length+' models',packed.length+' bytes');
}
for(const id of ['zun','cctv'])await pack(id,[await sourceCpuLandmark(id)]);
for(const lod of [1,2])await pack('cbd-'+lod,getCpuCbdMeshes(project,lod));
