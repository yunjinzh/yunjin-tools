import * as THREE from "three";
import { GLTFExporter } from "three/addons/exporters/GLTFExporter.js";

function saveBlob(blob: Blob, fileName: string) {
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = fileName;
  anchor.click();
  setTimeout(() => URL.revokeObjectURL(url), 2_000);
}

function safeName(value: string) {
  return value.replace(/[^\w\-\u4e00-\u9fff]+/g, "_").replace(/^_+|_+$/g, "") || "GeoPBF_Scene";
}

export async function exportGlb(root: THREE.Object3D, fileName: string) {
  const buffer = await createGlb(root);
  saveBlob(new Blob([buffer], { type: "model/gltf-binary" }), `${safeName(fileName)}.glb`);
  return buffer.byteLength;
}

export async function createGlb(root: THREE.Object3D) {
  const exporter = new GLTFExporter();
  const buffer = await exporter.parseAsync(root, { binary: true, onlyVisible: true, trs: false, maxTextureSize: 2048 });
  if (!(buffer instanceof ArrayBuffer)) throw new Error("GLB 导出器没有生成二进制数据。");
  const view = new DataView(buffer);
  if (view.byteLength < 20 || view.getUint32(0, true) !== 0x46546c67 || view.getUint32(4, true) !== 2) {
    throw new Error("GLB 文件头校验失败。");
  }
  return buffer;
}

type FbxMesh = {
  name: string;
  vertices: number[];
  polygonIndices: number[];
  normals: number[];
  color: THREE.Color;
  opacity: number;
};

function flattenMeshes(root: THREE.Object3D): FbxMesh[] {
  root.updateMatrixWorld(true);
  const meshes: FbxMesh[] = [];
  root.traverse((object) => {
    if (!(object instanceof THREE.Mesh) || !object.visible) return;
    const geometry = object.geometry.clone();
    if (!geometry.getAttribute("normal")) geometry.computeVertexNormals();
    const position = geometry.getAttribute("position") as THREE.BufferAttribute;
    const normal = geometry.getAttribute("normal") as THREE.BufferAttribute;
    const index = geometry.getIndex();
    const matrix = object.matrixWorld;
    const normalMatrix = new THREE.Matrix3().getNormalMatrix(matrix);
    const vertices: number[] = [];
    const vertexNormals: THREE.Vector3[] = [];
    const point = new THREE.Vector3();
    for (let i = 0; i < position.count; i += 1) {
      point.fromBufferAttribute(position, i).applyMatrix4(matrix);
      vertices.push(point.x, point.y, point.z);
      point.fromBufferAttribute(normal, i).applyMatrix3(normalMatrix).normalize();
      vertexNormals.push(point.clone());
    }
    const rawIndices = index ? Array.from(index.array, Number) : Array.from({ length: position.count }, (_, i) => i);
    const polygonIndices: number[] = [];
    const normals: number[] = [];
    for (let i = 0; i + 2 < rawIndices.length; i += 3) {
      const a = rawIndices[i];
      const b = rawIndices[i + 1];
      const c = rawIndices[i + 2];
      polygonIndices.push(a, b, -c - 1);
      for (const vertexIndex of [a, b, c]) {
        const n = vertexNormals[vertexIndex];
        normals.push(n.x, n.y, n.z);
      }
    }
    const material = Array.isArray(object.material) ? object.material[0] : object.material;
    const standard = material as THREE.MeshStandardMaterial;
    meshes.push({
      name: safeName(object.name || `Mesh_${meshes.length + 1}`),
      vertices,
      polygonIndices,
      normals,
      color: standard.color?.clone() || new THREE.Color(0xcccccc),
      opacity: standard.opacity ?? 1,
    });
    geometry.dispose();
  });
  return meshes;
}

function arrayBlock(values: number[], precision = 6) {
  const text = values.map((value) => Number.isInteger(value) ? String(value) : Number(value.toFixed(precision)).toString()).join(",");
  return `*${values.length} {\n            a: ${text}\n        }`;
}

function fbxHeader() {
  const now = new Date();
  return `; FBX 7.4.0 project file\n; Generated by GeoPBF Scene Builder\n\nFBXHeaderExtension:  {\n    FBXHeaderVersion: 1003\n    FBXVersion: 7400\n    Creator: "GeoPBF Scene Builder"\n    CreationTimeStamp:  {\n        Version: 1000\n        Year: ${now.getUTCFullYear()}\n        Month: ${now.getUTCMonth() + 1}\n        Day: ${now.getUTCDate()}\n        Hour: ${now.getUTCHours()}\n        Minute: ${now.getUTCMinutes()}\n        Second: ${now.getUTCSeconds()}\n        Millisecond: ${now.getUTCMilliseconds()}\n    }\n}\nGlobalSettings:  {\n    Version: 1000\n    Properties70:  {\n        P: "UpAxis", "int", "Integer", "",1\n        P: "UpAxisSign", "int", "Integer", "",1\n        P: "FrontAxis", "int", "Integer", "",2\n        P: "FrontAxisSign", "int", "Integer", "",-1\n        P: "CoordAxis", "int", "Integer", "",0\n        P: "CoordAxisSign", "int", "Integer", "",1\n        P: "UnitScaleFactor", "double", "Number", "",100\n        P: "OriginalUnitScaleFactor", "double", "Number", "",100\n    }\n}\n`;
}

export function createFbxAscii(root: THREE.Object3D) {
  const meshes = flattenMeshes(root);
  if (!meshes.length) throw new Error("场景中没有可导出的网格。");
  const baseId = 1_000_000;
  const objectCount = meshes.length * 3;
  const objects: string[] = [];
  const connections: string[] = [];
  meshes.forEach((mesh, index) => {
    const geometryId = baseId + index * 3;
    const modelId = geometryId + 1;
    const materialId = geometryId + 2;
    objects.push(`    Geometry: ${geometryId}, "Geometry::${mesh.name}", "Mesh" {\n        GeometryVersion: 124\n        Vertices: ${arrayBlock(mesh.vertices)}\n        PolygonVertexIndex: ${arrayBlock(mesh.polygonIndices, 0)}\n        LayerElementNormal: 0 {\n            Version: 101\n            Name: ""\n            MappingInformationType: "ByPolygonVertex"\n            ReferenceInformationType: "Direct"\n            Normals: ${arrayBlock(mesh.normals)}\n        }\n        LayerElementMaterial: 0 {\n            Version: 101\n            Name: ""\n            MappingInformationType: "AllSame"\n            ReferenceInformationType: "IndexToDirect"\n            Materials: *1 { a: 0 }\n        }\n        Layer: 0 {\n            Version: 100\n            LayerElement: { Type: "LayerElementNormal" TypedIndex: 0 }\n            LayerElement: { Type: "LayerElementMaterial" TypedIndex: 0 }\n        }\n    }`);
    objects.push(`    Model: ${modelId}, "Model::${mesh.name}", "Mesh" {\n        Version: 232\n        Properties70:  {\n            P: "Lcl Translation", "Lcl Translation", "", "A",0,0,0\n            P: "Lcl Rotation", "Lcl Rotation", "", "A",0,0,0\n            P: "Lcl Scaling", "Lcl Scaling", "", "A",1,1,1\n        }\n        Shading: T\n        Culling: "CullingOff"\n    }`);
    objects.push(`    Material: ${materialId}, "Material::${mesh.name}", "" {\n        Version: 102\n        ShadingModel: "phong"\n        MultiLayer: 0\n        Properties70:  {\n            P: "DiffuseColor", "Color", "", "A",${mesh.color.r},${mesh.color.g},${mesh.color.b}\n            P: "DiffuseFactor", "Number", "", "A",1\n            P: "TransparencyFactor", "Number", "", "A",${1 - mesh.opacity}\n        }\n    }`);
    connections.push(`    C: "OO",${modelId},0`);
    connections.push(`    C: "OO",${geometryId},${modelId}`);
    connections.push(`    C: "OO",${materialId},${modelId}`);
  });
  return `${fbxHeader()}Documents:  {\n    Count: 1\n    Document: 999, "Scene", "Scene" {\n        Properties70:  {\n            P: "SourceObject", "object", "", ""\n            P: "ActiveAnimStackName", "KString", "", "", ""\n        }\n        RootNode: 0\n    }\n}\nDefinitions:  {\n    Version: 100\n    Count: ${objectCount}\n    ObjectType: "Model" { Count: ${meshes.length} }\n    ObjectType: "Geometry" { Count: ${meshes.length} }\n    ObjectType: "Material" { Count: ${meshes.length} }\n}\nObjects:  {\n${objects.join("\n")}\n}\nConnections:  {\n${connections.join("\n")}\n}\n`;
}

export function exportFbx(root: THREE.Object3D, fileName: string) {
  const fbx = createFbxAscii(root);
  if (!fbx.startsWith("; FBX 7.4.0") || !fbx.includes("Objects:") || !fbx.includes("Connections:")) {
    throw new Error("FBX 文件结构校验失败。");
  }
  const blob = new Blob([fbx], { type: "application/octet-stream" });
  saveBlob(blob, `${safeName(fileName)}.fbx`);
  return blob.size;
}
